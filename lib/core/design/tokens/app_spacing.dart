/// Standard spacing tokens for padding, margin, and gaps.
abstract final class AppSpacing {
  /// 2dp micro spacing
  static const double xxs = 2;

  /// 4dp tight spacing
  static const double xs = 4;

  /// 8dp standard small spacing
  static const double sm = 8;

  /// 12dp medium spacing
  static const double md = 12;

  /// 16dp standard base layout spacing
  static const double lg = 16;

  /// 20dp expanded layout spacing
  static const double xl = 20;

  /// 24dp section spacing
  static const double xxl = 24;

  /// 32dp major section gap
  static const double xxxl = 32;

  /// 48dp major container gap or standard touch target size
  static const double touchTarget = 48;
}
